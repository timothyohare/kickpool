import { test, expect } from '@playwright/test';

test.describe('AI predictions (mocked)', () => {
  test('generates a prediction on demand without hitting Anthropic', async ({ page }) => {
    await page.goto('/fixtures/760415');

    await page.getByRole('button', { name: /Get AI Prediction/ }).click();

    // The deterministic MOCK_LLM prediction renders: a winner summary,
    // probability breakdown and a confidence line.
    await expect(page.getByText(/Predicted:/).first()).toBeVisible();
    await expect(page.getByText(/confidence/i)).toBeVisible();
    await expect(page.getByText(/Generated by Claude AI/)).toBeVisible();
  });
});
